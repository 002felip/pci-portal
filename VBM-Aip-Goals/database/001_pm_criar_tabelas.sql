/* ═══ GOAL CARD ═══ */
IF OBJECT_ID('PM.AIP_GOAL_CARD', 'U') IS NULL
CREATE TABLE PM.AIP_GOAL_CARD (
  ID_GOAL_CARD       INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AIP_GOAL_CARD PRIMARY KEY,
  CD_GOAL_CARD       VARCHAR(20)   NOT NULL,      -- GC-SAL-01 (único por ciclo)
  ID_META            INT           NOT NULL CONSTRAINT FK_AIP_GOAL_CARD_AIP_META REFERENCES PM.AIP_META (ID_META),
  ID_SITE            INT           NOT NULL,      -- IBP.SITES.ID_SITE
  TP_ESTADO          VARCHAR(20)   NOT NULL CONSTRAINT DF_AIP_GOAL_CARD_ESTADO DEFAULT ('RASCUNHO'),
  NO_VERSAO_OFICIAL  SMALLINT      NULL,
  DS_RASCUNHO        NVARCHAR(MAX) NULL,          -- JSON das 7 seções em edição
  CD_MATRICULA       VARCHAR(20)   NOT NULL,      -- quem alterou por último
  DT_ATUALIZACAO     DATETIME2(0)  NOT NULL CONSTRAINT DF_AIP_GOAL_CARD_ATUALIZACAO DEFAULT (SYSDATETIME()),
  CONSTRAINT UQ_AIP_GOAL_CARD UNIQUE (ID_META, ID_SITE),
  CONSTRAINT CK_AIP_GOAL_CARD_ESTADO CHECK (TP_ESTADO IN ('RASCUNHO', 'EM_APROVACAO', 'EM_REVISAO', 'APROVADO')),
  CONSTRAINT CK_AIP_GOAL_CARD_OFICIAL CHECK ((TP_ESTADO = 'APROVADO' AND NO_VERSAO_OFICIAL IS NOT NULL) OR (TP_ESTADO <> 'APROVADO' AND NO_VERSAO_OFICIAL IS NULL))
);
GO

IF OBJECT_ID('PM.AIP_GOAL_CARD_VERSAO', 'U') IS NULL
CREATE TABLE PM.AIP_GOAL_CARD_VERSAO (
  ID_VERSAO              INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AIP_GOAL_CARD_VERSAO PRIMARY KEY,
  ID_GOAL_CARD           INT            NOT NULL CONSTRAINT FK_AIP_GOAL_CARD_VERSAO_AIP_GOAL_CARD REFERENCES PM.AIP_GOAL_CARD (ID_GOAL_CARD),
  NO_VERSAO              SMALLINT       NOT NULL,
  TP_MOTIVO              VARCHAR(20)    NOT NULL,
  DS_CAMPOS              NVARCHAR(MAX)  NOT NULL,   -- JSON das 7 seções (imutável)
  DT_VERSAO              DATETIME2(0)   NOT NULL CONSTRAINT DF_AIP_GOAL_CARD_VERSAO_DT DEFAULT (SYSDATETIME()),
  CD_MATRICULA_AUTOR     VARCHAR(20)    NOT NULL,
  -- Decisão do grupo de aprovação (nível único), gravada uma vez
  TP_DECISAO             VARCHAR(20)    NULL,
  DS_COMENTARIO_DECISAO  NVARCHAR(4000) NULL,
  DS_REVISAO_SECOES      NVARCHAR(MAX)  NULL,       -- JSON: seções marcadas para ajuste e o comentário de cada uma
  DT_DECISAO             DATETIME2(0)   NULL,
  CD_MATRICULA_DECISAO   VARCHAR(20)    NULL,
  CONSTRAINT UQ_AIP_VERSAO UNIQUE (ID_GOAL_CARD, NO_VERSAO),
  CONSTRAINT CK_AIP_VERSAO_MOTIVO CHECK (TP_MOTIVO IN ('SUBMISSAO', 'RESUBMISSAO', 'REABERTURA')),
  CONSTRAINT CK_AIP_VERSAO_DECISAO CHECK (TP_DECISAO IN ('APROVADO', 'DEVOLVIDO')),
  CONSTRAINT CK_AIP_VERSAO_DECIDIDA CHECK (
    (TP_DECISAO IS NULL AND DT_DECISAO IS NULL AND CD_MATRICULA_DECISAO IS NULL)
    OR (TP_DECISAO IS NOT NULL AND DT_DECISAO IS NOT NULL AND CD_MATRICULA_DECISAO IS NOT NULL)),
  CONSTRAINT CK_AIP_VERSAO_COMENTARIO CHECK (TP_DECISAO IS NULL OR TP_DECISAO = 'APROVADO' OR DS_COMENTARIO_DECISAO IS NOT NULL),
  CONSTRAINT CK_AIP_VERSAO_REVISAO CHECK ((TP_DECISAO IS NULL AND DS_REVISAO_SECOES IS NULL) OR (TP_DECISAO IS NOT NULL AND DS_REVISAO_SECOES IS NOT NULL))
);
GO

