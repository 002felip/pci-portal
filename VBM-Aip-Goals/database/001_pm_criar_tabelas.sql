  SG_EXCECAO_VER        CHAR(1)        NOT NULL CONSTRAINT DF_AIP_CICLO_SITE_EXCECAO DEFAULT ('S'),
  CONSTRAINT PK_AIP_CICLO_SITE PRIMARY KEY (ID_CICLO, ID_SITE),
  CONSTRAINT CK_AIP_CICLO_SITE_SG_ATIVA CHECK (SG_ATIVA IN ('S', 'N')),
  CONSTRAINT CK_AIP_CICLO_SITE_SG_EXCECAO CHECK (SG_EXCECAO_VER IN ('S', 'N'))
);
GO

IF OBJECT_ID('PM.AIP_META', 'U') IS NULL
CREATE TABLE PM.AIP_META (
  ID_META         INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AIP_META PRIMARY KEY,
  ID_CICLO        INT           NOT NULL CONSTRAINT FK_AIP_META_AIP_CICLO REFERENCES PM.AIP_CICLO (ID_CICLO),
  CD_NIVEL        VARCHAR(20)   NOT NULL,          -- CEO, COO, BU
  NO_META         SMALLINT      NOT NULL,          -- BU nº 0 = resultado do scorecard do COO (pontos herdados)
  NM_TITULO       NVARCHAR(100) NOT NULL,
  TP_META         VARCHAR(20)   NOT NULL,
  TP_ORIENTACAO   VARCHAR(20)   NOT NULL,
  ID_META_ORIGEM  INT           NULL CONSTRAINT FK_AIP_META_AIP_META REFERENCES PM.AIP_META (ID_META),
  VL_PESO         DECIMAL(6,2)  NULL,              -- CEO e COO; a BU tem peso por site na AIP_META_PESO
  SG_ATIVA        CHAR(1)       NOT NULL CONSTRAINT DF_AIP_META_ATIVA DEFAULT ('S'),
  CONSTRAINT UQ_AIP_META UNIQUE (ID_CICLO, CD_NIVEL, NO_META),
  CONSTRAINT CK_AIP_META_SG_ATIVA CHECK (SG_ATIVA IN ('S', 'N')),
  CONSTRAINT CK_AIP_META_NIVEL CHECK (CD_NIVEL IN ('CEO', 'COO', 'BU')),
  CONSTRAINT CK_AIP_META_PESO_UNICO CHECK ((CD_NIVEL = 'BU' AND VL_PESO IS NULL) OR (CD_NIVEL <> 'BU' AND VL_PESO IS NOT NULL)),
  CONSTRAINT CK_AIP_META_TIPO CHECK (TP_META IN ('FORMULA', 'MARCOS')),
  CONSTRAINT CK_AIP_META_ORIENTACAO CHECK (TP_ORIENTACAO IN ('MAIOR', 'MENOR'))
);
GO

IF OBJECT_ID('PM.AIP_META_PESO', 'U') IS NULL
