DECLARE @ix TABLE (nome SYSNAME, tabela SYSNAME, colunas NVARCHAR(200));
INSERT @ix VALUES
  ('IX_AIP_CICLO_FK_AIP_CICLO',            'PM.AIP_CICLO',          'ID_CICLO_ORIGEM'),
  ('IX_AIP_CICLO_SITE_FK_SITES',           'PM.AIP_CICLO_SITE',     'ID_SITE'),
  ('IX_AIP_META_FK_AIP_META',              'PM.AIP_META',           'ID_META_ORIGEM'),
  ('IX_AIP_META_PESO_FK_SITES',            'PM.AIP_META_PESO',      'ID_SITE'),
  ('IX_AIP_PAPEL_FK_AIP_CICLO',            'PM.AIP_PAPEL',          'ID_CICLO'),
  ('IX_AIP_PAPEL_FK_SITES',                'PM.AIP_PAPEL',          'ID_SITE'),
  ('IX_AIP_PAPEL_MATRICULA',               'PM.AIP_PAPEL',          'CD_MATRICULA'),
  ('IX_AIP_GOAL_CARD_FK_SITES',            'PM.AIP_GOAL_CARD',      'ID_SITE'),
  ('IX_AIP_GOAL_CARD_CD',                  'PM.AIP_GOAL_CARD',      'CD_GOAL_CARD'),
  ('IX_AIP_EVENTO_LOG_FK_AIP_CICLO',       'PM.AIP_EVENTO_LOG',     'ID_CICLO, DT_EVENTO'),
  ('IX_AIP_EVENTO_LOG_FK_AIP_GOAL_CARD',   'PM.AIP_EVENTO_LOG',     'ID_GOAL_CARD'),
  ('IX_AIP_EVENTO_LOG_FK_AIP_EVENTO_LOG',  'PM.AIP_EVENTO_LOG',     'ID_EVENTO_PAI'),
  ('IX_AIP_NOTIFICACAO_FK_AIP_EVENTO_LOG', 'PM.AIP_NOTIFICACAO',    'ID_EVENTO');
DECLARE @n SYSNAME, @t SYSNAME, @c NVARCHAR(200), @sql NVARCHAR(MAX);
DECLARE cur CURSOR LOCAL FAST_FORWARD FOR SELECT nome, tabela, colunas FROM @ix;
OPEN cur; FETCH NEXT FROM cur INTO @n, @t, @c;
WHILE @@FETCH_STATUS = 0
BEGIN
  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = @n AND object_id = OBJECT_ID(@t))
  BEGIN
    SET @sql = N'CREATE INDEX ' + QUOTENAME(@n) + N' ON ' + @t + N' (' + @c + N');';
    EXEC sp_executesql @sql;
  END
  FETCH NEXT FROM cur INTO @n, @t, @c;
END
CLOSE cur; DEALLOCATE cur;
GO

