  CREATE UNIQUE INDEX UQ_AIP_PAPEL_BU ON PM.AIP_PAPEL (ID_CICLO, CD_MATRICULA, TP_GRUPO, ID_SITE) WHERE ID_SITE IS NOT NULL;
