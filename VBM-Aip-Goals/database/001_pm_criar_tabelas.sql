/* =====================================================================================================================
   AIP Goals — criação do schema PM e das 9 tabelas do AIP (modelo de 19/11/2026, database/der/).
   Banco: BDIBPBMSA_DEV (depois BDIBPBMSA_PRD), Azure SQL. Rode tudo de uma vez (SSMS / Azure Data Studio: F5).
   Pode rodar mais de uma vez: cria só o que ainda não existe.

   Diferenças em relação ao der/modelo.sql (PostgreSQL):
   - Schema próprio PM (as tabelas mantêm o prefixo AIP_).
   - CD_GOAL_CARD é único POR CICLO (a API garante): o mesmo código GC-SAL-01 volta em cada ciclo. No banco fica
     o índice IX_AIP_GOAL_CARD_CD; a unicidade real é (ID_META, ID_SITE).
   - Textos digitados em NVARCHAR (acentos e nomes estrangeiros); códigos em VARCHAR.
   - Datas de auditoria em SYSDATETIME() (horário do servidor do Azure SQL, UTC).
   - BU = site da IBP.SITES. As FKs para IBP.SITES só são criadas se a tabela existir neste banco.
   ===================================================================================================================== */
SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

IF SCHEMA_ID('PM') IS NULL EXEC('CREATE SCHEMA PM AUTHORIZATION dbo');
GO

/* ═══ CICLO ═══ */
IF OBJECT_ID('PM.AIP_CICLO', 'U') IS NULL
CREATE TABLE PM.AIP_CICLO (
  ID_CICLO                  INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AIP_CICLO PRIMARY KEY,
  NO_ANO                    SMALLINT       NOT NULL,
  NM_CICLO                  NVARCHAR(100)  NOT NULL,
  SG_STATUS                 CHAR(1)        NOT NULL CONSTRAINT DF_AIP_CICLO_STATUS DEFAULT ('S'),  -- S aberto, N fechado
  ID_CICLO_ORIGEM           INT            NULL CONSTRAINT FK_AIP_CICLO_AIP_CICLO REFERENCES PM.AIP_CICLO (ID_CICLO),
  DT_CRIACAO                DATETIME2(0)   NOT NULL CONSTRAINT DF_AIP_CICLO_CRIACAO DEFAULT (SYSDATETIME()),
  CD_MATRICULA_CRIACAO      VARCHAR(20)    NOT NULL,
  DT_FECHAMENTO             DATETIME2(0)   NULL,
  CD_MATRICULA_FECHAMENTO   VARCHAR(20)    NULL,
  -- Jornada do ciclo: 4 etapas fixas (em branco no ciclo recém-aberto até o administrador escolher as datas, D-35)
  DT_INI_DESDOBRAMENTO      DATE NULL,
  DT_FIM_DESDOBRAMENTO      DATE NULL,
  DT_INI_PROPOSTA           DATE NULL,
  DT_FIM_PROPOSTA           DATE NULL,
  DT_INI_CALIBRACAO         DATE NULL,
  DT_FIM_CALIBRACAO         DATE NULL,
  DT_INI_OFICIAL            DATE NULL,
  DT_FIM_OFICIAL            DATE NULL,
  -- Desdobramento CEO → COO → BU: cada um fecha 100 pts; parte vem do resultado do nível acima
  QTDE_PONTOS_HERDADOS_COO  SMALLINT NOT NULL,
  QTDE_PONTOS_HERDADOS_BU   SMALLINT NOT NULL,
  CONSTRAINT UQ_AIP_CICLO_ANO UNIQUE (NO_ANO),
  CONSTRAINT CK_AIP_CICLO_JORNADA CHECK (
    DT_INI_DESDOBRAMENTO < DT_FIM_DESDOBRAMENTO AND DT_INI_PROPOSTA < DT_FIM_PROPOSTA
    AND DT_INI_CALIBRACAO < DT_FIM_CALIBRACAO AND DT_INI_OFICIAL < DT_FIM_OFICIAL
    AND DT_INI_DESDOBRAMENTO <= DT_INI_PROPOSTA AND DT_INI_PROPOSTA <= DT_INI_CALIBRACAO AND DT_INI_CALIBRACAO <= DT_INI_OFICIAL),
  CONSTRAINT CK_AIP_CICLO_HERDADOS CHECK (QTDE_PONTOS_HERDADOS_COO BETWEEN 0 AND 99 AND QTDE_PONTOS_HERDADOS_BU BETWEEN 0 AND 99),
  CONSTRAINT CK_AIP_CICLO_ANO CHECK (NO_ANO BETWEEN 2020 AND 2100),
  CONSTRAINT CK_AIP_CICLO_STATUS CHECK (SG_STATUS IN ('S', 'N')),
  CONSTRAINT CK_AIP_CICLO_FECHAMENTO CHECK (
    (SG_STATUS = 'S' AND DT_FECHAMENTO IS NULL AND CD_MATRICULA_FECHAMENTO IS NULL)
    OR (SG_STATUS = 'N' AND DT_FECHAMENTO IS NOT NULL AND CD_MATRICULA_FECHAMENTO IS NOT NULL))
);
GO
-- Só um ciclo aberto por vez
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UQ_AIP_CICLO_UM_ABERTO' AND object_id = OBJECT_ID('PM.AIP_CICLO'))
  CREATE UNIQUE INDEX UQ_AIP_CICLO_UM_ABERTO ON PM.AIP_CICLO (SG_STATUS) WHERE SG_STATUS = 'S';
GO

/* ═══ DESDOBRAMENTO ═══ */
-- Site (BU) no ciclo: participa, diretor e exceção (telas Business Units e Exceções)
IF OBJECT_ID('PM.AIP_CICLO_SITE', 'U') IS NULL
CREATE TABLE PM.AIP_CICLO_SITE (
  ID_CICLO              INT            NOT NULL CONSTRAINT FK_AIP_CICLO_SITE_AIP_CICLO REFERENCES PM.AIP_CICLO (ID_CICLO),
