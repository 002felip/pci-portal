    EXEC(N'ALTER TABLE PM.AIP_PAPEL ADD CONSTRAINT FK_AIP_PAPEL_SITES FOREIGN KEY (ID_SITE) REFERENCES IBP.SITES (ID_SITE)');
  IF OBJECT_ID('PM.FK_AIP_GOAL_CARD_SITES', 'F') IS NULL
