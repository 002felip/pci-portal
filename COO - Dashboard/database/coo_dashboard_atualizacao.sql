DECLARE 
    @DT_REF DATE,
    @DT_INI DATE,
    @DT_FIM DATE;

SET @DT_INI = '2025-01-01';
SET @DT_FIM = CAST(DATEADD(MONTH, 0, CONCAT(YEAR(DATEFROMPARTS(YEAR(DATEADD(MONTH, -1, GETDATE()-1)), MONTH(DATEADD(MONTH, -1, GETDATE()-1)), 1)), '-12-01')) AS DATE);
SET @DT_REF = DATEADD(MONTH, -1, (SELECT DT_INI FROM IBP.CONTROLE_PROCESSOS WHERE ID_PROCESSO = 2));





;WITH Months AS (
    SELECT DATEFROMPARTS(YEAR(@DT_INI), MONTH(@DT_INI), 1) AS DT_REF
    UNION ALL
    SELECT DATEADD(MONTH, 1, DT_REF)
    FROM Months
    WHERE DATEADD(MONTH, 1, DT_REF) <= @DT_FIM
),
CTE AS (
    SELECT 
        M.DT_REF,
        DASH.ID_SISTEMA,
        DASH.ID_SITE,
        DASH.ID_OPERACAO,
        DASH.ID_KPI,
        DASH.ID_ORDEM,
        DASH.NM_KPIS_DASH,
        CASE 
            WHEN LPVC.DT_ATUALIZACAO IS NULL THEN 0  -- sem atualização
            WHEN PVC.DT_REF < @DT_REF THEN 1
            WHEN DATEFROMPARTS(YEAR(DATEADD(MONTH, -1, LPVC.DT_ATUALIZACAO)), MONTH(DATEADD(MONTH, -1, LPVC.DT_ATUALIZACAO)), 1) >= @DT_REF THEN 1 
            ELSE 0 
        END AS VALIDATE,
        CASE 
            WHEN LPVC.DT_ATUALIZACAO IS NULL THEN 'Pending final updates'  -- <<<<< regra principal
            WHEN PVC.DT_REF < @DT_REF THEN '.'
            WHEN DATEFROMPARTS(YEAR(DATEADD(MONTH, -1, LPVC.DT_ATUALIZACAO)), MONTH(DATEADD(MONTH, -1, LPVC.DT_ATUALIZACAO)), 1) >= @DT_REF THEN '.' 
            ELSE 'Pending final updates'
        END AS DS_VALIDATE,
        LPVC.DT_ATUALIZACAO,
        ROW_NUMBER() OVER (
            PARTITION BY M.DT_REF, DASH.ID_SISTEMA, DASH.ID_SITE, DASH.ID_OPERACAO, DASH.ID_KPI 
            ORDER BY LPVC.DT_ATUALIZACAO DESC
        ) AS rn
    FROM Months M
    CROSS JOIN IBP.DASHBOARD DASH
    LEFT JOIN IBP.PEDRAVISAOCONSOLIDADA PVC 
        ON CONCAT(DASH.ID_SISTEMA, DASH.ID_SITE, DASH.ID_OPERACAO, DASH.ID_KPI) = CONCAT(PVC.ID_SISTEMA, PVC.ID_SITE, PVC.ID_OPERACAO, PVC.ID_KPI)  
        AND PVC.DT_REF = M.DT_REF
    LEFT JOIN IBP.LOG_PEDRAVISAOCONSOLIDADA LPVC 
        ON CONCAT(PVC.ID_SISTEMA, PVC.ID_SITE, PVC.ID_OPERACAO, PVC.ID_KPI) = CONCAT(LPVC.ID_SISTEMA, LPVC.ID_SITE, LPVC.ID_OPERACAO, LPVC.ID_KPI) 
    WHERE DASH.ID_DASH = 15
)
SELECT 
    DT_REF,
    ID_SISTEMA,
    ID_SITE,
    ID_OPERACAO,
    ID_KPI,
    ID_ORDEM,
    NM_KPIS_DASH,
    VALIDATE,
    DS_VALIDATE,
    DT_ATUALIZACAO
FROM CTE
WHERE rn = 1
OPTION (MAXRECURSION 0);
