/* ════════════════════════════════════════════════════════════════════
   COO Business Units Dashboard — validação das regras do VBM Performance Studio
   Banco: BDIBPBMSA_PRD · SOMENTE LEITURA (só tabelas temporárias #)

   Compara, por KPI do dashboard 15, o valor que o COO mostra hoje com o
   valor que a carga do VBM (VBM-Performance-Studio/database/003_carga_mensal.sql)
   gravaria em IBP.PHUB_PERFORMANCESTUDIO:

     0. Datas de referência   COO: GETDATE()-2 - 1 mês · VBM: IBP.CONTROLE_PROCESSOS
     1. Trimestre             COO: IBP.PEDRAVISAOTRIMESTRE · VBM: soma dos meses de PEDRAVISAOCONSOLIDADA
     2. Ano                   COO: IBP.PEDRAVISAOANO       · VBM: soma dos meses de PEDRAVISAOCONSOLIDADA
     3. Mês do ciclo (Act)    COO: realizado até o mês ANTERIOR ao ciclo · VBM: realizado até o mês do ciclo
     4. Cadastro repetido     KPI com mais de uma linha em IBP.DASHBOARD (somaria em dobro)
     5. Resumo

   Regra do Act/Fcst no VBM: VL_REAL (NULL = 0) até o último mês realizado,
   VL_PROJ depois. VL_AF_VBM_CORTE_COO aplica a mesma soma com o corte do COO
   (um mês antes): se ela bate com o COO e VL_AF_VBM não, a diferença vem só
   do corte do realizado, não da tabela de trimestre/ano.
   ════════════════════════════════════════════════════════════════════ */
SET NOCOUNT ON;

DECLARE @ID_DASH INT   = 15;
DECLARE @TOL     FLOAT = 0.000001;  -- diferença relativa tolerada (arredondamento de FLOAT)

-- Mês do ciclo do COO = último mês realizado (mesma regra das queries do COO)
DECLARE @DT_REAL DATE = DATEADD(MONTH, -1, CAST(GETDATE() - 2 AS DATE));
SET @DT_REAL = DATEFROMPARTS(YEAR(@DT_REAL), MONTH(@DT_REAL), 1);
DECLARE @DT_CORTE_COO DATE = DATEADD(MONTH, -1, @DT_REAL);           -- até onde o COO usa VL_REAL hoje
DECLARE @DT_INI DATE = DATEFROMPARTS(YEAR(@DT_REAL) - 1, 1, 1);       -- = '2025-01-01' do COO em 2026
DECLARE @DT_FIM DATE = DATEFROMPARTS(YEAR(DATEADD(MONTH, 1, @DT_REAL)), 12, 1);

-- ── 0. Datas de referência ────────────────────────────────────────────
SELECT
  '0. Datas' AS VERIFICACAO,
  @DT_REAL AS MES_CICLO_COO,
  @DT_CORTE_COO AS CORTE_REALIZADO_COO,
  CP.DT_INI AS CONTROLE_PROCESSOS_DT_INI,
  DATEADD(MONTH, -1, DATEFROMPARTS(YEAR(CP.DT_INI), MONTH(CP.DT_INI), 1)) AS DT_REF_VBM,
  DATEADD(MONTH, -2, DATEFROMPARTS(YEAR(CP.DT_INI), MONTH(CP.DT_INI), 1)) AS MES_REALIZADO_VBM,
  CASE WHEN DATEADD(MONTH, -2, DATEFROMPARTS(YEAR(CP.DT_INI), MONTH(CP.DT_INI), 1)) = @DT_REAL
       THEN 'Igual' ELSE 'Diferente' END AS SITUACAO
FROM (SELECT 1 AS X) U
LEFT JOIN IBP.CONTROLE_PROCESSOS CP ON CP.ID_PROCESSO = 2;

-- ── KPIs do dashboard (uma linha por KPI) ─────────────────────────────
IF OBJECT_ID('tempdb..#K') IS NOT NULL DROP TABLE #K;
SELECT ID_SISTEMA, ID_SITE, ID_OPERACAO, ID_KPI,
       MAX(NM_KPIS_DASH) AS NM_KPI, MAX(VL_FATOR) AS VL_FATOR, COUNT(*) AS QT_CADASTRO
INTO #K
FROM IBP.DASHBOARD
WHERE ID_DASH = @ID_DASH
GROUP BY ID_SISTEMA, ID_SITE, ID_OPERACAO, ID_KPI;

-- ── Meses de PEDRAVISAOCONSOLIDADA com as regras do Act/Fcst ──────────
IF OBJECT_ID('tempdb..#M') IS NOT NULL DROP TABLE #M;
SELECT
  K.ID_SISTEMA, K.ID_SITE, K.ID_OPERACAO, K.ID_KPI, PVC.DT_REF,
  PVC.VL_ORC * K.VL_FATOR AS VL_B,
  CASE WHEN PVC.DT_REF <= @DT_REAL      THEN ISNULL(PVC.VL_REAL, 0) * K.VL_FATOR ELSE PVC.VL_PROJ * K.VL_FATOR END AS VL_AF_VBM,
  CASE WHEN PVC.DT_REF <= @DT_CORTE_COO THEN ISNULL(PVC.VL_REAL, 0) * K.VL_FATOR ELSE PVC.VL_PROJ * K.VL_FATOR END AS VL_AF_CORTE_COO,
  PVC.VL_REAL * K.VL_FATOR AS VL_REAL,
  PVC.VL_PROJ * K.VL_FATOR AS VL_PROJ
INTO #M
FROM IBP.PEDRAVISAOCONSOLIDADA PVC
INNER JOIN #K K
  ON K.ID_SISTEMA = PVC.ID_SISTEMA AND K.ID_SITE = PVC.ID_SITE
  AND K.ID_OPERACAO = PVC.ID_OPERACAO AND K.ID_KPI = PVC.ID_KPI
WHERE PVC.DT_REF BETWEEN @DT_INI AND @DT_FIM;

-- ── 1. Trimestre ──────────────────────────────────────────────────────
IF OBJECT_ID('tempdb..#T') IS NOT NULL DROP TABLE #T;
WITH COO AS (
  SELECT PVT.ID_SISTEMA, PVT.ID_SITE, PVT.ID_OPERACAO, PVT.ID_KPI,
         YEAR(PVT.DT_REF) AS ANO, DATEPART(QUARTER, PVT.DT_REF) AS PERIODO,
         SUM(PVT.VL_ORC * K.VL_FATOR) AS VL_B, SUM(PVT.VL_PROJ * K.VL_FATOR) AS VL_AF, COUNT(*) AS QT_LINHAS
  FROM IBP.PEDRAVISAOTRIMESTRE PVT
  INNER JOIN #K K
    ON K.ID_SISTEMA = PVT.ID_SISTEMA AND K.ID_SITE = PVT.ID_SITE
    AND K.ID_OPERACAO = PVT.ID_OPERACAO AND K.ID_KPI = PVT.ID_KPI
  WHERE PVT.DT_REF BETWEEN @DT_INI AND @DT_FIM
  GROUP BY PVT.ID_SISTEMA, PVT.ID_SITE, PVT.ID_OPERACAO, PVT.ID_KPI, YEAR(PVT.DT_REF), DATEPART(QUARTER, PVT.DT_REF)
), VBM AS (
  SELECT ID_SISTEMA, ID_SITE, ID_OPERACAO, ID_KPI, YEAR(DT_REF) AS ANO, DATEPART(QUARTER, DT_REF) AS PERIODO,
         SUM(VL_B) AS VL_B, SUM(VL_AF_VBM) AS VL_AF, SUM(VL_AF_CORTE_COO) AS VL_AF_CORTE_COO
  FROM #M
  GROUP BY ID_SISTEMA, ID_SITE, ID_OPERACAO, ID_KPI, YEAR(DT_REF), DATEPART(QUARTER, DT_REF)
)
SELECT 'QUARTER' AS CD_PERIODO,
       COALESCE(C.ID_SISTEMA, V.ID_SISTEMA) AS ID_SISTEMA, COALESCE(C.ID_SITE, V.ID_SITE) AS ID_SITE,
       COALESCE(C.ID_OPERACAO, V.ID_OPERACAO) AS ID_OPERACAO, COALESCE(C.ID_KPI, V.ID_KPI) AS ID_KPI,
       COALESCE(C.ANO, V.ANO) AS ANO, COALESCE(C.PERIODO, V.PERIODO) AS PERIODO,
       C.VL_B AS VL_B_COO, V.VL_B AS VL_B_VBM,
       C.VL_AF AS VL_AF_COO, V.VL_AF AS VL_AF_VBM, V.VL_AF_CORTE_COO AS VL_AF_VBM_CORTE_COO,
       C.QT_LINHAS AS QT_LINHAS_COO,
       CASE WHEN C.ID_KPI IS NULL THEN 1 ELSE 0 END AS SO_VBM,
       CASE WHEN V.ID_KPI IS NULL THEN 1 ELSE 0 END AS SO_COO
INTO #T
FROM COO C
FULL OUTER JOIN VBM V
  ON V.ID_SISTEMA = C.ID_SISTEMA AND V.ID_SITE = C.ID_SITE AND V.ID_OPERACAO = C.ID_OPERACAO
  AND V.ID_KPI = C.ID_KPI AND V.ANO = C.ANO AND V.PERIODO = C.PERIODO;

-- ── 2. Ano ────────────────────────────────────────────────────────────
WITH COO AS (
  SELECT PVA.ID_SISTEMA, PVA.ID_SITE, PVA.ID_OPERACAO, PVA.ID_KPI, PVA.ANO, PVA.ANO AS PERIODO,
         SUM(PVA.VL_ORC * K.VL_FATOR) AS VL_B, SUM(PVA.VL_PROJ * K.VL_FATOR) AS VL_AF, COUNT(*) AS QT_LINHAS
  FROM IBP.PEDRAVISAOANO PVA
  INNER JOIN #K K
    ON K.ID_SISTEMA = PVA.ID_SISTEMA AND K.ID_SITE = PVA.ID_SITE
    AND K.ID_OPERACAO = PVA.ID_OPERACAO AND K.ID_KPI = PVA.ID_KPI
  WHERE PVA.ANO BETWEEN YEAR(@DT_INI) AND YEAR(@DT_FIM)
  GROUP BY PVA.ID_SISTEMA, PVA.ID_SITE, PVA.ID_OPERACAO, PVA.ID_KPI, PVA.ANO
), VBM AS (
  SELECT ID_SISTEMA, ID_SITE, ID_OPERACAO, ID_KPI, YEAR(DT_REF) AS ANO, YEAR(DT_REF) AS PERIODO,
         SUM(VL_B) AS VL_B, SUM(VL_AF_VBM) AS VL_AF, SUM(VL_AF_CORTE_COO) AS VL_AF_CORTE_COO
  FROM #M
  GROUP BY ID_SISTEMA, ID_SITE, ID_OPERACAO, ID_KPI, YEAR(DT_REF)
)
INSERT INTO #T
SELECT 'YEAR',
       COALESCE(C.ID_SISTEMA, V.ID_SISTEMA), COALESCE(C.ID_SITE, V.ID_SITE),
       COALESCE(C.ID_OPERACAO, V.ID_OPERACAO), COALESCE(C.ID_KPI, V.ID_KPI),
       COALESCE(C.ANO, V.ANO), COALESCE(C.PERIODO, V.PERIODO),
       C.VL_B, V.VL_B, C.VL_AF, V.VL_AF, V.VL_AF_CORTE_COO, C.QT_LINHAS,
       CASE WHEN C.ID_KPI IS NULL THEN 1 ELSE 0 END,
       CASE WHEN V.ID_KPI IS NULL THEN 1 ELSE 0 END
FROM COO C
FULL OUTER JOIN VBM V
  ON V.ID_SISTEMA = C.ID_SISTEMA AND V.ID_SITE = C.ID_SITE AND V.ID_OPERACAO = C.ID_OPERACAO
  AND V.ID_KPI = C.ID_KPI AND V.ANO = C.ANO AND V.PERIODO = C.PERIODO;

-- Classificação de cada linha (trimestre e ano)
IF OBJECT_ID('tempdb..#TC') IS NOT NULL DROP TABLE #TC;
SELECT T.*,
  CASE
    WHEN SO_VBM = 1 THEN 'Só no VBM'
    WHEN SO_COO = 1 THEN 'Só no COO'
    WHEN ABS(ISNULL(VL_B_COO, 0) - ISNULL(VL_B_VBM, 0)) > @TOL * (1 + ABS(ISNULL(VL_B_VBM, 0))) THEN 'Budget diferente'
    WHEN ABS(ISNULL(VL_AF_COO, 0) - ISNULL(VL_AF_VBM, 0)) <= @TOL * (1 + ABS(ISNULL(VL_AF_VBM, 0))) THEN 'Igual'
    WHEN ABS(ISNULL(VL_AF_COO, 0) - ISNULL(VL_AF_VBM_CORTE_COO, 0)) <= @TOL * (1 + ABS(ISNULL(VL_AF_VBM_CORTE_COO, 0))) THEN 'Act/Fcst diferente: só o corte do realizado'
    ELSE 'Act/Fcst diferente: origem'
  END AS SITUACAO
INTO #TC
FROM #T T;

SELECT '1-2. Trimestre e ano (só divergências)' AS VERIFICACAO, TC.SITUACAO, TC.CD_PERIODO, TC.ANO, TC.PERIODO,
       TC.ID_SISTEMA, TC.ID_SITE, TC.ID_OPERACAO, TC.ID_KPI, K.NM_KPI,
       TC.VL_B_COO, TC.VL_B_VBM, TC.VL_AF_COO, TC.VL_AF_VBM, TC.VL_AF_VBM_CORTE_COO,
       ISNULL(TC.VL_AF_VBM, 0) - ISNULL(TC.VL_AF_COO, 0) AS DIF_AF, TC.QT_LINHAS_COO
FROM #TC TC
LEFT JOIN #K K
  ON K.ID_SISTEMA = TC.ID_SISTEMA AND K.ID_SITE = TC.ID_SITE AND K.ID_OPERACAO = TC.ID_OPERACAO AND K.ID_KPI = TC.ID_KPI
WHERE TC.SITUACAO <> 'Igual'
ORDER BY TC.CD_PERIODO, TC.ANO, TC.PERIODO, TC.ID_SITE, TC.ID_OPERACAO, TC.ID_KPI;

-- ── 3. Mês do ciclo: Act/Fcst ─────────────────────────────────────────
SELECT '3. Mês do ciclo (só divergências)' AS VERIFICACAO, M.DT_REF,
       M.ID_SISTEMA, M.ID_SITE, M.ID_OPERACAO, M.ID_KPI, K.NM_KPI,
       M.VL_AF_CORTE_COO AS VL_AF_COO, M.VL_AF_VBM,
       M.VL_REAL, M.VL_PROJ,
       CASE WHEN M.VL_REAL IS NULL THEN 'Sem realizado: VBM mostraria 0' ELSE 'Realizado no lugar da projeção' END AS SITUACAO
FROM #M M
INNER JOIN #K K
  ON K.ID_SISTEMA = M.ID_SISTEMA AND K.ID_SITE = M.ID_SITE AND K.ID_OPERACAO = M.ID_OPERACAO AND K.ID_KPI = M.ID_KPI
WHERE M.DT_REF = @DT_REAL
  AND ABS(ISNULL(M.VL_AF_CORTE_COO, 0) - ISNULL(M.VL_AF_VBM, 0)) > @TOL * (1 + ABS(ISNULL(M.VL_AF_VBM, 0)))
ORDER BY M.ID_SITE, M.ID_OPERACAO, M.ID_KPI;

-- ── 4. Cadastro repetido em IBP.DASHBOARD ─────────────────────────────
SELECT '4. Cadastro repetido' AS VERIFICACAO, ID_SISTEMA, ID_SITE, ID_OPERACAO, ID_KPI, NM_KPI, QT_CADASTRO
FROM #K
WHERE QT_CADASTRO > 1
ORDER BY ID_SITE, ID_OPERACAO, ID_KPI;

-- ── 5. Resumo ─────────────────────────────────────────────────────────
SELECT '5. Resumo' AS VERIFICACAO, CD_PERIODO, SITUACAO, COUNT(*) AS LINHAS
FROM #TC
GROUP BY CD_PERIODO, SITUACAO
UNION ALL
SELECT '5. Resumo', 'MONTH (ciclo)',
       CASE WHEN ABS(ISNULL(VL_AF_CORTE_COO, 0) - ISNULL(VL_AF_VBM, 0)) > @TOL * (1 + ABS(ISNULL(VL_AF_VBM, 0)))
            THEN 'Act/Fcst diferente: só o corte do realizado' ELSE 'Igual' END,
       COUNT(*)
FROM #M
WHERE DT_REF = @DT_REAL
GROUP BY CASE WHEN ABS(ISNULL(VL_AF_CORTE_COO, 0) - ISNULL(VL_AF_VBM, 0)) > @TOL * (1 + ABS(ISNULL(VL_AF_VBM, 0)))
              THEN 'Act/Fcst diferente: só o corte do realizado' ELSE 'Igual' END
ORDER BY 2, 3;

DROP TABLE #TC; DROP TABLE #T; DROP TABLE #M; DROP TABLE #K;
