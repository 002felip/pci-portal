/* ════════════════════════════════════════════════════════════════════
   VBM Health of the Business — VERIFICAÇÃO do que está atualizado (só leitura, não grava nada)
   Banco: BDIBPBMSA_PRD · rodar quando quiser conferir, antes ou depois da carga (003)

   Uma linha por indicador do dashboard (IBP.DASHBOARD, ID_DASH 16), com:
     DT_ULTIMO_LOG / SG_STATUS  última atualização em IBP.LOG_PEDRAVISAOCONSOLIDADA e a situação na
                                mesma regra do 007 (e do COO): 'S' se >= referência, senão 'N'
     ULT_MES ... ULT_ANO        último período que cada tabela de origem tem para o indicador
                                (CONSOLIDADA = mês, TRIMESTRE, YEARTODATE = YTD, YEARTOGO = YTG, ANO)
     TEM_MES / TEM_YTD / TEM_YTG  'S' se a origem já tem o mês de referência
     YTD_REPETIDO               'S' se o YTD do mês de referência é igual ao do mês anterior
                                (sinal de que o mês ainda não entrou no YTD)
     DS_SITUACAO                'Atualizado' ou a lista do que falta
   No fim, um resumo e a carga gravada (SG_STATUS e DT_ATUALIZACAO) por indicador.

   Referência = mês do ciclo = DATEADD(MONTH, -1, GETDATE()-2), no 1º dia do mês (06/11/2026 → 2026-10-01)
   ════════════════════════════════════════════════════════════════════ */
SET NOCOUNT ON;

DECLARE @ID_DASH INT  = 16;
DECLARE @DT_REF  DATE = DATEADD(MONTH, -1, GETDATE() - 2);
SET @DT_REF = DATEFROMPARTS(YEAR(@DT_REF), MONTH(@DT_REF), 1);
DECLARE @DT_ANT  DATE = DATEADD(MONTH, -1, @DT_REF);
DECLARE @DT_CARGA DATE = DATEFROMPARTS(YEAR(GETDATE() - 2), MONTH(GETDATE() - 2), 1);

IF OBJECT_ID('tempdb..#V') IS NOT NULL DROP TABLE #V;

WITH K AS (
  SELECT DASH.ID_SISTEMA, DASH.ID_SITE, DASH.ID_OPERACAO, DASH.ID_KPI, MIN(DASH.ID_ORDEM) AS ID_ORDEM,
         MAX(LTRIM(RTRIM(DASH.NM_KPIS_DASH))) AS NM_KPI
  FROM IBP.DASHBOARD DASH
  WHERE DASH.ID_DASH = @ID_DASH
  GROUP BY DASH.ID_SISTEMA, DASH.ID_SITE, DASH.ID_OPERACAO, DASH.ID_KPI
)
SELECT
  K.ID_ORDEM, K.ID_SISTEMA, K.ID_SITE, LTRIM(RTRIM(S.NM_SITE)) AS NM_SITE, K.ID_OPERACAO, K.ID_KPI, K.NM_KPI,
  LG.DT_ULTIMO_LOG,
  CASE WHEN LG.DT_ULTIMO_LOG >= @DT_REF THEN 'S' ELSE 'N' END AS SG_STATUS,
  MES.ULT_MES, TRI.ULT_TRIMESTRE, YTD.ULT_YTD, YTG.ULT_YTG, ANO.ULT_ANO,
  CASE WHEN MES.ULT_MES >= @DT_REF THEN 'S' ELSE 'N' END AS TEM_MES,
  CASE WHEN YTD.ULT_YTD >= @DT_REF THEN 'S' ELSE 'N' END AS TEM_YTD,
  CASE WHEN YTG.ULT_YTG >= @DT_REF THEN 'S' ELSE 'N' END AS TEM_YTG,
  CASE WHEN YR.ORC IS NOT NULL AND YR.ORC = YA.ORC AND ISNULL(YR.REAL, 0) = ISNULL(YA.REAL, 0) THEN 'S' ELSE 'N' END AS YTD_REPETIDO
INTO #V
FROM K
LEFT JOIN IBP.SITES S ON S.ID_SITE = K.ID_SITE
OUTER APPLY (SELECT MAX(L.DT_ATUALIZACAO) AS DT_ULTIMO_LOG FROM IBP.LOG_PEDRAVISAOCONSOLIDADA L
             WHERE L.ID_SISTEMA = K.ID_SISTEMA AND L.ID_SITE = K.ID_SITE AND L.ID_OPERACAO = K.ID_OPERACAO AND L.ID_KPI = K.ID_KPI) LG
OUTER APPLY (SELECT MAX(P.DT_REF) AS ULT_MES FROM IBP.PEDRAVISAOCONSOLIDADA P
             WHERE P.ID_SISTEMA = K.ID_SISTEMA AND P.ID_SITE = K.ID_SITE AND P.ID_OPERACAO = K.ID_OPERACAO AND P.ID_KPI = K.ID_KPI AND P.DT_REF <= @DT_REF) MES
OUTER APPLY (SELECT MAX(P.DT_REF) AS ULT_TRIMESTRE FROM IBP.PEDRAVISAOTRIMESTRE P
             WHERE P.ID_SISTEMA = K.ID_SISTEMA AND P.ID_SITE = K.ID_SITE AND P.ID_OPERACAO = K.ID_OPERACAO AND P.ID_KPI = K.ID_KPI AND P.DT_REF <= @DT_REF) TRI
OUTER APPLY (SELECT MAX(P.DT_REF) AS ULT_YTD FROM IBP.PEDRAVISAOYEARTODATE P
             WHERE P.ID_SISTEMA = K.ID_SISTEMA AND P.ID_SITE = K.ID_SITE AND P.ID_OPERACAO = K.ID_OPERACAO AND P.ID_KPI = K.ID_KPI AND P.DT_REF <= @DT_REF) YTD
OUTER APPLY (SELECT MAX(P.DT_REF) AS ULT_YTG FROM IBP.PEDRAVISAOYEARTOGO P
             WHERE P.ID_SISTEMA = K.ID_SISTEMA AND P.ID_SITE = K.ID_SITE AND P.ID_OPERACAO = K.ID_OPERACAO AND P.ID_KPI = K.ID_KPI AND P.DT_REF <= @DT_REF) YTG
OUTER APPLY (SELECT MAX(P.ANO) AS ULT_ANO FROM IBP.PEDRAVISAOANO P
             WHERE P.ID_SISTEMA = K.ID_SISTEMA AND P.ID_SITE = K.ID_SITE AND P.ID_OPERACAO = K.ID_OPERACAO AND P.ID_KPI = K.ID_KPI) ANO
OUTER APPLY (SELECT SUM(P.VL_ORC) AS ORC, SUM(P.VL_REAL) AS REAL FROM IBP.PEDRAVISAOYEARTODATE P
             WHERE P.ID_SISTEMA = K.ID_SISTEMA AND P.ID_SITE = K.ID_SITE AND P.ID_OPERACAO = K.ID_OPERACAO AND P.ID_KPI = K.ID_KPI AND P.DT_REF = @DT_REF) YR
OUTER APPLY (SELECT SUM(P.VL_ORC) AS ORC, SUM(P.VL_REAL) AS REAL FROM IBP.PEDRAVISAOYEARTODATE P
             WHERE P.ID_SISTEMA = K.ID_SISTEMA AND P.ID_SITE = K.ID_SITE AND P.ID_OPERACAO = K.ID_OPERACAO AND P.ID_KPI = K.ID_KPI AND P.DT_REF = @DT_ANT) YA;

-- 1) situação por indicador
SELECT DT_REFERENCIA = @DT_REF, V.*,
  DS_SITUACAO = CASE WHEN V.SG_STATUS = 'S' AND V.TEM_MES = 'S' AND V.TEM_YTD = 'S' AND V.TEM_YTG = 'S' AND V.YTD_REPETIDO = 'N' THEN 'Atualizado'
    ELSE STUFF(
      CASE WHEN V.SG_STATUS = 'N' THEN ' · ' + CASE WHEN V.DT_ULTIMO_LOG IS NULL THEN 'sem registro no log' ELSE 'log anterior à referência' END ELSE '' END +
      CASE WHEN V.TEM_MES = 'N' THEN ' · sem o mês na CONSOLIDADA' ELSE '' END +
      CASE WHEN V.TEM_YTD = 'N' THEN ' · sem o mês no YTD' ELSE '' END +
      CASE WHEN V.YTD_REPETIDO = 'S' THEN ' · YTD igual ao mês anterior' ELSE '' END +
      CASE WHEN V.TEM_YTG = 'N' THEN ' · sem o mês no YTG' ELSE '' END, 1, 3, '') END
FROM #V V
ORDER BY CASE WHEN V.SG_STATUS = 'S' AND V.TEM_MES = 'S' AND V.TEM_YTD = 'S' AND V.TEM_YTG = 'S' AND V.YTD_REPETIDO = 'N' THEN 1 ELSE 0 END,
  V.ID_SITE, V.ID_ORDEM, V.ID_KPI;

-- 2) resumo
SELECT DT_REFERENCIA = @DT_REF, INDICADORES = COUNT(*),
  ATUALIZADOS      = SUM(CASE WHEN SG_STATUS = 'S' AND TEM_MES = 'S' AND TEM_YTD = 'S' AND TEM_YTG = 'S' AND YTD_REPETIDO = 'N' THEN 1 ELSE 0 END),
  LOG_PENDENTE     = SUM(CASE WHEN SG_STATUS = 'N' THEN 1 ELSE 0 END),
  SEM_MES          = SUM(CASE WHEN TEM_MES = 'N' THEN 1 ELSE 0 END),
  SEM_YTD          = SUM(CASE WHEN TEM_YTD = 'N' THEN 1 ELSE 0 END),
  YTD_REPETIDO     = SUM(CASE WHEN YTD_REPETIDO = 'S' THEN 1 ELSE 0 END),
  SEM_YTG          = SUM(CASE WHEN TEM_YTG = 'N' THEN 1 ELSE 0 END)
FROM #V;

-- 3) o que a carga gravada tem hoje (SG_STATUS e DT_ATUALIZACAO gravados pelo 007; NULL = 007 ainda não rodou)
SELECT R.DT_REF AS DT_CARGA, R.ID_SITE, R.ID_OPERACAO, R.ID_KPI, MIN(R.SG_STATUS) AS SG_STATUS, MAX(R.DT_ATUALIZACAO) AS DT_ATUALIZACAO,
  SUM(CASE WHEN R.CD_PERIODO = 'YTG' THEN 1 ELSE 0 END) AS LINHAS_YTG, COUNT(*) AS LINHAS
FROM IBP.PHUB_PERFORMANCESTUDIO R
WHERE R.ID_DASH = @ID_DASH AND R.DT_REF = (SELECT MAX(DT_REF) FROM IBP.PHUB_PERFORMANCESTUDIO WHERE ID_DASH = @ID_DASH AND DT_REF <= @DT_CARGA)
GROUP BY R.DT_REF, R.ID_SITE, R.ID_OPERACAO, R.ID_KPI
ORDER BY R.ID_SITE, R.ID_KPI;

DROP TABLE #V;
